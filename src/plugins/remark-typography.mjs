/**
 * Русская микротипографика для постов.
 *
 * Работает на этапе рендера по текстовым узлам mdast — исходные .mdx не
 * меняются. Код, инлайн-код, ссылки-урлы и JSX-атрибуты не трогаются:
 * обходим только узлы типа `text`.
 *
 * Что делает (правила из practicaltypography.com + русская традиция):
 *  - многоточие одним знаком: ... → …
 *  - дефис вместо тире: «слово - слово» → «слово — слово»
 *  - диапазоны через короткое тире: 1990-2000 → 1990–2000
 *  - прямые кавычки → «ёлочки», вложенные → „лапки“
 *  - прямой апостроф → ’
 *  - неразрывные пробелы: после коротких предлогов и союзов, между числом и
 *    словом, перед длинным тире, после № и §
 *  - схлопывает подряд идущие пробелы
 */

const NBSP = ' ';

/** Узлы, внутрь которых лезть нельзя. */
const OPAQUE = new Set(['code', 'inlineCode', 'html', 'mdxjsEsm']);

/** Прямые кавычки → «ёлочки», вложенные пары → „лапки“. */
function quotes(value) {
  let depth = 0;

  return value.replace(/"/g, () => {
    // Открывающая, если глубина чётная; на нечётной — закрываем.
    const open = depth % 2 === 0;
    const pair = depth < 2 ? ['«', '»'] : ['„', '“'];

    depth += open ? 1 : -1;

    return open ? pair[0] : pair[1];
  });
}

function typographize(value) {
  let s = value;

  // Несколько пробелов подряд — это опечатка, а не приём вёрстки.
  s = s.replace(/ {2,}/g, ' ');

  // Многоточие.
  s = s.replace(/\.{3,}/g, '…');

  // Дефис или двойной дефис между словами — на самом деле тире.
  s = s.replace(/(\s)-{1,2}(\s)/g, '$1—$2');

  // Диапазоны чисел — короткое тире без пробелов.
  s = s.replace(/(\d)\s*-\s*(?=\d)/g, '$1–');

  // Английские «лапки», набранные руками, — тоже кавычки: текст русский.
  s = s.replace(/[“]/g, '«').replace(/[”]/g, '»');

  s = quotes(s);

  // Апостроф.
  s = s.replace(/(\p{L})'(\p{L})/gu, '$1’$2');

  // --- Неразрывные пробелы ---

  // Предлоги и союзы в один-два знака липнут к следующему слову.
  // Лукбехайнд, а не захват: иначе в цепочке «и в лесу» второй предлог
  // остался бы без неразрывного пробела.
  s = s.replace(
    /(?<=^|[\s(«„—-])([а-яёa-z]{1,2}) (?=[«„(]?\p{L})/giu,
    `$1${NBSP}`,
  );

  // Число не отрывается от того, что за ним: «5 км», «2026 году».
  s = s.replace(/(\d) (?=\p{L})/gu, `$1${NBSP}`);

  // № и § не остаются в конце строки.
  s = s.replace(/([№§]) *(?=\d)/g, `$1${NBSP}`);

  // Тире не начинает строку — держится за предыдущее слово.
  s = s.replace(/(\S) —/g, `$1${NBSP}—`);

  return s;
}

export default function remarkTypography() {
  return (tree) => {
    const walk = (node) => {
      if (!node || OPAQUE.has(node.type)) return;

      if (node.type === 'text' && typeof node.value === 'string') {
        node.value = typographize(node.value);
        return;
      }

      if (Array.isArray(node.children)) {
        node.children.forEach(walk);
      }
    };

    walk(tree);
  };
}
